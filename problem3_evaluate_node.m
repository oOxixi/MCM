function node = evaluate_node( ...
    children, ...
    p_node, ...
    assemblyCost, ...
    detectCost, ...
    disassemblyCost, ...
    inspectNode, ...
    disassembleNode)

%% =========================================================
% evaluate_node.m
%
% 功能：
% 计算一个“半成品节点”的质量概率和期望成本
%
% 例如：
%
% 零件1、2、3
%       ↓
%     半成品1
%
% ---------------------------------------------------------
% 输入：
%
% children
%   下级节点结构体数组
%
%   每个下级节点至少需要包含：
%
%   children(i).C
%       当前生产策略下，获得该下级产品的期望成本
%
%   children(i).g
%       当前生产策略下，该下级产品的合格概率
%
%   children(i).detectCost
%       检测该下级产品一次所需费用
%
%   children(i).inspected
%       该下级产品在进入当前装配前是否已经检测
%       1 = 已检测
%       0 = 未检测
%
%   children(i).R
%       已经确认该下级产品为次品后，
%       将其处理成一个“确认合格产品”的期望成本
%
%
% p_node
%   当所有下级产品均合格时，
%   当前节点仍成为次品的概率
%
% assemblyCost
%   当前节点装配成本
%
% detectCost
%   当前节点检测成本
%
% disassemblyCost
%   当前节点拆解费用
%
% inspectNode
%   当前节点是否检测
%   1 = 检测
%   0 = 不检测
%
% disassembleNode
%   当前节点检测出不合格后是否拆解
%   1 = 拆解
%   0 = 不拆解
%
% ---------------------------------------------------------
% 输出 node：
%
% node.C
%   按当前正常生产策略，获得一个当前节点产品的期望成本
%
% node.g
%   该产品进入上一层时的合格概率
%
% node.K
%   从零开始获得一个“确认合格当前节点”的期望成本
%
% node.R
%   已经确认当前节点为次品以后，
%   将其处理成一个确认合格节点的期望成本
%
% node.detectCost
%   当前节点检测成本
%
% node.inspected
%   当前节点是否已检测
%
% node.rawGoodRate
%   当前节点第一次装配后的实际合格率
%
% node.rawDefectRate
%   当前节点第一次装配后的实际次品率
%
% node.recoveryCost
%   当前节点拆解以后，
%   对原先未检测下级产品进行检测、修复的条件期望成本
%
%% =========================================================


%% =========================================================
% 1. 保存当前节点基本信息
%% =========================================================

node.detectCost = detectCost;

node.inspected = inspectNode;


%% =========================================================
% 2. 计算所有下级产品的成本之和
%    以及全部下级产品合格的概率
%% =========================================================

childTotalCost = 0;

childAllGoodRate = 1;


for i = 1:length(children)

    childTotalCost = ...
        childTotalCost + children(i).C;

    childAllGoodRate = ...
        childAllGoodRate * children(i).g;

end


%% =========================================================
% 3. 当前节点一次装配的基础成本
%
% 注意：
% 此处暂时不包含当前节点检测费用
%% =========================================================

BaseCost = ...
    childTotalCost + assemblyCost;


%% =========================================================
% 4. 当前节点实际合格率
%
% 当前节点合格需要：
%
% 所有下级产品都合格
% ×
% 当前装配过程没有失败
%% =========================================================

G = ...
    childAllGoodRate * (1-p_node);


q = 1-G;


node.rawGoodRate = G;

node.rawDefectRate = q;


%% =========================================================
% 5. 当前节点已经被确认不合格以后，
%    若进行拆解，对下级产品进行处理
%
% 规则：
%
% 之前检测过 → 不重复检测
%
% 之前未检测 → 拆解以后必须检测
%
% 检测发现下级产品为次品 →
% 调用该下级节点自己的 R 进行修复/替换
%% =========================================================

RecoveryCost = 0;


if q > 0

    for i = 1:length(children)

        %% -------------------------------------------------
        % 已经检测过：
        %
        % 进入当前装配时已经确认合格，
        % 且拆解不会损坏，因此无需再次检测
        %% -------------------------------------------------

        if children(i).inspected == 1

            continue;

        end


        %% -------------------------------------------------
        % 没检测过：
        %
        % 拆解后先检测一次
        %% -------------------------------------------------

        testCost = ...
            children(i).detectCost;


        %% -------------------------------------------------
        % 条件概率
        %
        % P(下级i为次品 | 当前节点为次品)
        %
        % 因为：
        %
        % 下级i为次品
        %     =>
        % 当前节点一定为次品
        %
        % 所以：
        %
        % P(B_i | D)
        % =
        % P(B_i) / P(D)
        %
        % =
        % (1-g_i) / q
        %% -------------------------------------------------

        probBadGivenNodeBad = ...
            (1-children(i).g) / q;


        %% 防止浮点数计算导致略大于1

        probBadGivenNodeBad = ...
            min( ...
            max(probBadGivenNodeBad,0), ...
            1);


        %% -------------------------------------------------
        % 如果检测后发现这个下级产品是坏的，
        %
        % children(i).R
        %
        % 表示：
        %
        % 已知它坏了以后，
        % 把它变成一个确认合格下级产品的期望成本
        %% -------------------------------------------------

        RecoveryCost = ...
            RecoveryCost ...
            + testCost ...
            + probBadGivenNodeBad ...
            * children(i).R;

    end

end


node.recoveryCost = RecoveryCost;


%% =========================================================
% 6. 定义 W
%
% 假设经过第一次拆解处理以后，
% 所有下级产品都已经成为“确认合格品”。
%
% 此时再次生产当前节点，
% 若仍出现次品，
% 原因只能是当前节点自身装配失败。
%
%
% W =
% 已经拥有全部确认合格下级产品以后，
% 得到一个确认合格当前节点的期望后续成本
%% =========================================================


if disassembleNode == 1

    %% -----------------------------------------------------
    % 递推：
    %
    % W
    % =
    % 装配成本
    % + 检测成本
    % + p_node*(拆解费用 + W)
    %
    % 所以：
    %
    % W =
    %
    % [装配成本 + 检测成本
    %  + p_node*拆解费用]
    %
    % / (1-p_node)
    %% -----------------------------------------------------

    W = ...
        ( ...
        assemblyCost ...
        + detectCost ...
        + p_node*disassemblyCost ...
        ) ...
        / (1-p_node);

else

    W = NaN;

end


node.W = W;


%% =========================================================
% 7. 计算 R
%
% R：
%
% 当前节点已经被确认是次品以后，
% 得到一个确认合格当前节点的期望处理成本
%% =========================================================


if disassembleNode == 1

    %% -----------------------------------------------------
    % 选择拆解
    %
    % 已知当前产品是次品：
    %
    % 1. 支付拆解费
    % 2. 处理原来没有检测的下级产品
    % 3. 得到全部确认合格下级产品
    % 4. 再进入 W 状态
    %% -----------------------------------------------------

    node.R = ...
        disassemblyCost ...
        + RecoveryCost ...
        + W;


else

    %% -----------------------------------------------------
    % 如果不拆解：
    %
    % 已知当前节点坏了以后直接整体报废，
    % 需要重新从头生产一个确认合格的当前节点。
    %
    % 此处的值要等 K 算出来以后确定
    %% -----------------------------------------------------

    node.R = NaN;

end


%% =========================================================
% 8. 计算 K
%
% K：
%
% 从零开始，
% 得到一个“确认合格当前节点”的期望成本
%
% 无论当前节点平时是否检测，
% K 都表示为了得到一个明确合格节点时的成本。
%% =========================================================


if disassembleNode == 0

    %% -----------------------------------------------------
    % 不拆解：
    %
    % 每次从头生产：
    %
    % 下级产品成本
    % + 当前节点装配成本
    % + 当前节点检测成本
    %
    % 一次成功概率为 G
    %
    % 所以：
    %
    % K = (BaseCost + detectCost)/G
    %% -----------------------------------------------------

    node.K = ...
        (BaseCost + detectCost) / G;


    %% 已知坏件直接报废以后，
    % 就重新从零生产一个确认合格节点

    node.R = node.K;


else

    %% -----------------------------------------------------
    % 拆解：
    %
    % 第一次：
    %
    % BaseCost + detectCost
    %
    % 如果失败，概率q，
    % 再付 node.R
    %% -----------------------------------------------------

    node.K = ...
        BaseCost ...
        + detectCost ...
        + q*node.R;

end


%% =========================================================
% 9. 根据“当前节点是否检测”
%    决定它进入上一道工序时的成本和质量概率
%% =========================================================


if inspectNode == 1

    %% -----------------------------------------------------
    % 当前节点检测
    %
    % 不合格的已经被处理掉，
    % 所以上一级拿到的一定是合格品
    %% -----------------------------------------------------

    node.C = node.K;

    node.g = 1;


else

    %% -----------------------------------------------------
    % 当前节点不检测
    %
    % 只生产一次就进入下一道工序，
    % 因此保留实际次品风险
    %% -----------------------------------------------------

    node.C = BaseCost;

    node.g = G;

end


end