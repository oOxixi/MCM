function final = evaluate_final( ...
    children, ...
    p_final, ...
    assemblyCost, ...
    detectCost, ...
    disassemblyCost, ...
    replacementLoss, ...
    inspectFinal, ...
    disassembleFinal)

%% =========================================================
% evaluate_final.m
%
% 功能：
%
% 计算最终成品节点的期望成本、合格率和利润计算所需信息
%
% 生产结构：
%
% 半成品1、半成品2、半成品3
%              ↓
%           最终成品
%              ↓
%             市场
%
% ---------------------------------------------------------
% 输入：
%
% children
%   三个半成品节点
%
% 每个children(i)至少包含：
%
% children(i).C
%   当前策略下该半成品进入最终装配时的成本
%
% children(i).g
%   该半成品进入最终装配时的合格概率
%
% children(i).detectCost
%   检测该半成品所需费用
%
% children(i).inspected
%   该半成品在进入最终装配前是否已经检测
%
% children(i).R
%   已知该半成品为次品后，
%   将其处理成确认合格半成品的期望成本
%
%
% p_final
%   三个半成品均合格时，
%   最终装配仍产生次品的概率
%
% assemblyCost
%   最终成品装配费用
%
% detectCost
%   最终成品检测费用
%
% disassemblyCost
%   最终成品拆解费用
%
% replacementLoss
%   次品流入市场以后产生的调换损失
%
% inspectFinal
%   是否检测最终成品
%
% disassembleFinal
%   不合格最终成品是否拆解
%
% ---------------------------------------------------------
% 输出 final：
%
% final.C
%   最终成功交付一件合格产品的期望总成本
%
% final.goodRate
%   第一次最终装配的实际合格率
%
% final.defectRate
%   第一次最终装配的实际次品率
%
% final.recoveryCost
%   最终成品拆解以后，
%   对之前未检测半成品进行检测和处理的条件期望成本
%
% final.W
%   已经拥有三个确认合格半成品以后，
%   从重新装配到最终成功交付的期望成本
%
%% =========================================================


%% =========================================================
% 1. 三个半成品的成本总和与联合合格概率
%% =========================================================

childTotalCost = 0;

childAllGoodRate = 1;


for i = 1:length(children)

    childTotalCost = ...
        childTotalCost + children(i).C;

    childAllGoodRate = ...
        childAllGoodRate * children(i).g;

end


%% =========================================================
% 2. 最终产品一次生产的基础成本
%
% 暂时不包含最终成品检测费
%% =========================================================

BaseCost = ...
    childTotalCost + assemblyCost;


%% =========================================================
% 3. 第一次最终装配的实际合格率
%
% 三个半成品全部合格
% ×
% 最终装配过程成功
%% =========================================================

G = ...
    childAllGoodRate ...
    * (1-p_final);


q = 1-G;


final.goodRate = G;

final.defectRate = q;


%% =========================================================
% 4. 最终成品已经确定为次品且选择拆解时，
%    对三个半成品的处理成本
%
% 规则：
%
% 之前检测过的半成品：
% 不重复检测
%
% 之前未检测的半成品：
% 拆解后必须检测
%
% 如果检测发现该半成品为次品：
% 使用 children(i).R 进行处理
%% =========================================================

RecoveryCost = 0;


if q > 0

    for i = 1:length(children)


        %% -------------------------------------------------
        % 原来已经检测过
        %% -------------------------------------------------

        if children(i).inspected == 1

            continue;

        end


        %% -------------------------------------------------
        % 原来没有检测过：
        % 拆解后检测一次
        %% -------------------------------------------------

        testCost = ...
            children(i).detectCost;


        %% -------------------------------------------------
        % 条件概率：
        %
        % P(半成品i坏 | 最终成品坏)
        %
        % 因为：
        %
        % 半成品i坏
        % =>
        % 最终成品一定坏
        %
        % 所以：
        %
        % P(B_i | D)
        %
        % =
        % (1-g_i) / q
        %% -------------------------------------------------

        probBadGivenFinalBad = ...
            (1-children(i).g) / q;


        probBadGivenFinalBad = ...
            min( ...
            max(probBadGivenFinalBad,0), ...
            1);


        %% -------------------------------------------------
        % 回收处理期望成本
        %% -------------------------------------------------

        RecoveryCost = ...
            RecoveryCost ...
            + testCost ...
            + probBadGivenFinalBad ...
            * children(i).R;

    end

end


final.recoveryCost = RecoveryCost;


%% =========================================================
% 5. 根据最终成品是否检测、是否拆解，
%    分成四种情况
%% =========================================================


%% =========================================================
% 情况 A：
%
% 最终成品检测
% +
% 不合格产品不拆解
%
% inspectFinal = 1
% disassembleFinal = 0
%% =========================================================

if inspectFinal == 1 && disassembleFinal == 0

    %% -----------------------------------------------------
    % 每次生产：
    %
    % 半成品成本
    % + 最终装配费
    % + 最终检测费
    %
    % 成功概率为 G
    %
    % 如果检测为次品：
    % 整件报废，从头重新生产
    %% -----------------------------------------------------

    final.C = ...
        ( ...
        BaseCost + detectCost ...
        ) ...
        / G;


    final.W = NaN;


%% =========================================================
% 情况 B：
%
% 最终成品检测
% +
% 不合格产品拆解
%% =========================================================

elseif inspectFinal == 1 && disassembleFinal == 1

    %% -----------------------------------------------------
    % 首次失败并处理以后，
    % 三个半成品均成为确认合格半成品。
    %
    % 定义 W：
    %
    % 已拥有三个确认合格半成品后，
    % 从重新装配开始，
    % 直到检测得到合格最终产品的期望成本。
    %
    %
    % W =
    %
    % assemblyCost
    % + detectCost
    % + p_final*(disassemblyCost + W)
    %
    % 得：
    %
    % W =
    %
    % [assemblyCost
    %  + detectCost
    %  + p_final*disassemblyCost]
    %
    % / (1-p_final)
    %% -----------------------------------------------------

    W = ...
        ( ...
        assemblyCost ...
        + detectCost ...
        + p_final*disassemblyCost ...
        ) ...
        / (1-p_final);


    final.W = W;


    %% -----------------------------------------------------
    % 第一轮：
    %
    % BaseCost + detectCost
    %
    % q概率失败：
    %
    % 拆解费
    % + 未检测半成品回收处理成本
    % + W
    %% -----------------------------------------------------

    final.C = ...
        BaseCost ...
        + detectCost ...
        + q * ...
        ( ...
        disassemblyCost ...
        + RecoveryCost ...
        + W ...
        );


%% =========================================================
% 情况 C：
%
% 最终成品不检测
% +
% 次品退回后不拆解
%% =========================================================

elseif inspectFinal == 0 && disassembleFinal == 0

    %% -----------------------------------------------------
    % 不检测时：
    %
    % 产品直接进入市场。
    %
    % 若合格：
    % 完成一次成功交付。
    %
    % 若次品：
    %
    % 客户退回
    % + 企业承担调换损失
    % + 次品整体报废
    % + 从头重新生产
    %
    %
    % 设最终期望成本为 E：
    %
    % E =
    %
    % BaseCost
    % + q*(replacementLoss + E)
    %
    % 解得：
    %
    % E =
    %
    % [BaseCost + q*replacementLoss] / G
    %% -----------------------------------------------------

    final.C = ...
        ( ...
        BaseCost ...
        + q*replacementLoss ...
        ) ...
        / G;


    final.W = NaN;


%% =========================================================
% 情况 D：
%
% 最终成品不检测
% +
% 客户退回次品后进行拆解
%% =========================================================

else

    %% -----------------------------------------------------
    % 首次最终产品不检测，
    % 所有产品直接进入市场。
    %
    % 如果是次品：
    %
    % 1. 客户退回
    % 2. 企业承担调换损失
    % 3. 拆解最终产品
    % 4. 检测原来没检测过的半成品
    % 5. 修复/替换发现的坏半成品
    % 6. 三个半成品均成为确认合格
    % 7. 重新装配
    %% -----------------------------------------------------


    %% -----------------------------------------------------
    % 已经拥有三个确认合格半成品以后，
    % 因为最终产品仍然选择“不检测”，
    % 所以装配后的产品仍直接进入市场。
    %
    % 此时若失败：
    %
    % 失败只能来自最终装配过程，
    % 概率为 p_final。
    %
    % 会产生：
    %
    % replacementLoss
    % +
    % disassemblyCost
    %
    % 然后重新装配。
    %
    %
    % W =
    %
    % assemblyCost
    % +
    % p_final*
    % (replacementLoss + disassemblyCost + W)
    %
    %
    % 得：
    %
    % W =
    %
    % [assemblyCost
    %  + p_final*(replacementLoss+disassemblyCost)]
    %
    % /(1-p_final)
    %% -----------------------------------------------------

    W = ...
        ( ...
        assemblyCost ...
        + p_final * ...
        ( ...
        replacementLoss ...
        + disassemblyCost ...
        ) ...
        ) ...
        / (1-p_final);


    final.W = W;


    %% -----------------------------------------------------
    % 第一轮生产：
    %
    % 先支付 BaseCost。
    %
    % q概率为次品：
    %
    % replacementLoss
    % + disassemblyCost
    % + RecoveryCost
    % + W
    %% -----------------------------------------------------

    final.C = ...
        BaseCost ...
        + q * ...
        ( ...
        replacementLoss ...
        + disassemblyCost ...
        + RecoveryCost ...
        + W ...
        );

end


end