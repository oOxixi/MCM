%% =========================================================
% 2024 B题 问题2
% 生产过程决策优化 —— 改进版
%
% 决策变量：
% x1 = 是否在初始装配前检测零件1
% x2 = 是否在初始装配前检测零件2
% x3 = 是否检测成品
% x4 = 是否拆解不合格成品
%
% 0 = 否
% 1 = 是
%
% 拆解后的规则：
% 1. 原来已经检测过的零件，不重复检测；
% 2. 原来没有检测过的零件，拆解后必须检测；
% 3. 回收件检测为次品后丢弃，并重新购买、检测，
%    直到获得合格零件；
% 4. 一旦经过上述处理，两个回收零件均成为已知合格件；
% 5. 此后若因装配原因再次失败，拆解后无需重复检测。
%
% 优化目标：
% 最大化最终成功交付一件合格成品的期望利润
%% =========================================================


%% =========================================================
% 1. 表1 六种情况数据
%
% 每列依次为：
%
% p1   零件1次品率
% a1   零件1购买单价
% d1   零件1检测成本
%
% p2   零件2次品率
% a2   零件2购买单价
% d2   零件2检测成本
%
% pf   正品零件装配后成品次品率
% Ca   装配成本
% Cf   成品检测成本
%
% S    市场售价
% L    调换损失
% Cd   拆解费用
%% =========================================================

Data = [

    0.10  4  2   0.10  18  3   0.10  6  3   56   6   5;
    0.20  4  2   0.20  18  3   0.20  6  3   56   6   5;
    0.10  4  2   0.10  18  3   0.10  6  3   56  30   5;
    0.20  4  1   0.20  18  1   0.20  6  2   56  30   5;
    0.10  4  8   0.20  18  1   0.10  6  2   56  10   5;
    0.05  4  2   0.05  18  3   0.05  6  3   56  10  40

];


%% =========================================================
% 2. 初始化结果矩阵
%
% 6种情况 × 16种策略 = 96种组合
%
% 保存：
% 1  CaseID
% 2  x1
% 3  x2
% 4  x3
% 5  x4
% 6  初始成品次品率 q
% 7  初始零件1成本
% 8  初始零件2成本
% 9  首次失败后回收零件处理成本
% 10 已知两个好零件后的后续期望成本
% 11 期望失败次数
% 12 期望市场退换次数
% 13 期望总成本
% 14 期望利润
%% =========================================================

numCases = size(Data,1);
numStrategies = 16;

all_result = nan(numCases*numStrategies,14);

row_id = 0;


%% =========================================================
% 3. 六种情况逐一计算
%% =========================================================

for case_id = 1:numCases

    %% 当前参数

    p1 = Data(case_id,1);
    a1 = Data(case_id,2);
    d1 = Data(case_id,3);

    p2 = Data(case_id,4);
    a2 = Data(case_id,5);
    d2 = Data(case_id,6);

    pf = Data(case_id,7);

    Ca = Data(case_id,8);
    Cf = Data(case_id,9);

    S  = Data(case_id,10);
    L  = Data(case_id,11);
    Cd = Data(case_id,12);


    %% =====================================================
    % 4. 枚举16种决策
    %% =====================================================

    for x1 = 0:1

        for x2 = 0:1

            for x3 = 0:1

                for x4 = 0:1

                    row_id = row_id + 1;


                    %% =====================================
                    % 5. 初始进入装配的零件合格概率
                    %% =====================================

                    if x1 == 1
                        g1 = 1;
                    else
                        g1 = 1 - p1;
                    end


                    if x2 == 1
                        g2 = 1;
                    else
                        g2 = 1 - p2;
                    end


                    %% =====================================
                    % 6. 初始获得零件的期望成本
                    %
                    % 若初始检测：
                    % 不合格则重新购买并检测直到合格
                    %
                    % 若初始不检测：
                    % 买一个直接进入装配
                    %% =====================================

                    if x1 == 1

                        C1_init = ...
                            (a1 + d1) / (1 - p1);

                    else

                        C1_init = a1;

                    end


                    if x2 == 1

                        C2_init = ...
                            (a2 + d2) / (1 - p2);

                    else

                        C2_init = a2;

                    end


                    %% =====================================
                    % 7. 初始产品合格率和次品率
                    %
                    % 两个零件均合格
                    % 且装配过程成功
                    %% =====================================

                    G = ...
                        g1 * ...
                        g2 * ...
                        (1 - pf);

                    q = 1 - G;


                    %% =====================================
                    % 8. 每次装配尝试成本
                    %% =====================================

                    AssemblyCost = ...
                        Ca + x3*Cf;


                    %% =====================================
                    % 9. 不拆解策略
                    %% =====================================

                    if x4 == 0

                        % 一次完整初始生产成本
                        C0 = ...
                            C1_init + ...
                            C2_init + ...
                            AssemblyCost;


                        % 若失败：
                        %
                        % x3 = 1：
                        % 企业内部检测发现，无调换损失
                        %
                        % x3 = 0：
                        % 次品进入市场，产生调换损失
                        %
                        % 产品报废后重新从头生产

                        ExpectedCost = ...
                            ( ...
                            C0 + ...
                            q*(1-x3)*L ...
                            ) / G;


                        %% 期望失败次数
                        %
                        % 几何分布：
                        %
                        % q / G

                        ExpectedFailNum = ...
                            q / G;


                        %% 期望市场退换次数

                        ExpectedReturnNum = ...
                            (1-x3) * ExpectedFailNum;


                        %% 不拆解时无回收处理

                        RecoveryCost = 0;

                        FutureKnownGoodCost = NaN;


                    %% =====================================
                    % 10. 拆解策略
                    %% =====================================

                    else

                        %% ---------------------------------
                        % 第一次生产成本
                        %% ---------------------------------

                        InitialCost = ...
                            C1_init + ...
                            C2_init + ...
                            AssemblyCost;


                        %% ---------------------------------
                        % 已知第一次产品失败以后，
                        % 对原来没检测过的零件进行检测
                        %
                        % 若零件原来已经检测：
                        % 拆解不会损伤，因此不再检测
                        %
                        % 若原来没检测：
                        % 拆解后必须检测
                        %% ---------------------------------

                        RecoveryCost = 0;


                        %% =================================
                        % 零件1回收处理成本
                        %% =================================

                        if x1 == 0

                            % 已知成品失败条件下：
                            %
                            % 零件1为次品的条件概率：
                            %
                            % P(part1坏 | 成品坏)
                            %
                            % 因为只要part1坏，
                            % 成品一定坏，
                            %
                            % 所以：
                            %
                            % P(part1坏 | D) = p1/q

                            ProbBad1GivenFail = ...
                                p1 / q;


                            % 防止极小数值误差超过1
                            ProbBad1GivenFail = ...
                                min(max(ProbBad1GivenFail,0),1);


                            % 若拆出零件1是坏件，
                            % 则重新购买并检测，
                            % 直到得到合格零件

                            CostNewGoodPart1 = ...
                                (a1 + d1) / (1 - p1);


                            % 无论好坏，
                            % 拆出来的这个零件首先要检测一次
                            %
                            % 若坏：
                            % 再增加重新获得一个合格件的成本

                            RecoveryPart1 = ...
                                d1 + ...
                                ProbBad1GivenFail * ...
                                CostNewGoodPart1;


                            RecoveryCost = ...
                                RecoveryCost + ...
                                RecoveryPart1;

                        end


                        %% =================================
                        % 零件2回收处理成本
                        %% =================================

                        if x2 == 0

                            ProbBad2GivenFail = ...
                                p2 / q;


                            ProbBad2GivenFail = ...
                                min(max(ProbBad2GivenFail,0),1);


                            CostNewGoodPart2 = ...
                                (a2 + d2) / (1 - p2);


                            RecoveryPart2 = ...
                                d2 + ...
                                ProbBad2GivenFail * ...
                                CostNewGoodPart2;


                            RecoveryCost = ...
                                RecoveryCost + ...
                                RecoveryPart2;

                        end


                        %% =================================
                        % 经过首次失败后的检测处理后：
                        %
                        % 两个零件均已经成为“已知合格”
                        %
                        % 此后产品失败只能来自装配过程
                        %% =================================


                        %% ---------------------------------
                        % 定义 W：
                        %
                        % 已经拥有两个已知合格零件，
                        % 从下一次装配开始，
                        % 直到成功交付的期望成本
                        %
                        % W =
                        %
                        % AssemblyCost
                        % +
                        % pf*[失败处理 + W]
                        %
                        % 因此：
                        %
                        % W =
                        %
                        % [AssemblyCost
                        %  + pf*(Cd+(1-x3)L)]
                        % / (1-pf)
                        %% ---------------------------------

                        FutureKnownGoodCost = ...
                            ( ...
                            AssemblyCost + ...
                            pf * ...
                            (Cd + (1-x3)*L) ...
                            ) ...
                            / (1 - pf);


                        %% =================================
                        % 总期望成本
                        %
                        % 先付初始生产成本
                        %
                        % 若第一次产品失败（概率q）：
                        %
                        % 1. 若未检测成品，发生调换损失
                        % 2. 支付拆解费用
                        % 3. 处理原来未检测的零件
                        % 4. 进入“两个已知合格零件”状态
                        %% =================================

                        ExpectedCost = ...
                            InitialCost + ...
                            q * ...
                            ( ...
                            (1-x3)*L + ...
                            Cd + ...
                            RecoveryCost + ...
                            FutureKnownGoodCost ...
                            );


                        %% =================================
                        % 期望失败次数
                        %
                        % 初始失败概率为q
                        %
                        % 一旦初始失败，
                        % 后续已知好零件装配失败次数期望：
                        %
                        % pf/(1-pf)
                        %
                        % 因此：
                        %
                        % E(Fail) =
                        %
                        % q * [1 + pf/(1-pf)]
                        %
                        % = q/(1-pf)
                        %% =================================

                        ExpectedFailNum = ...
                            q / (1 - pf);


                        %% 市场退换次数

                        ExpectedReturnNum = ...
                            (1-x3) * ...
                            ExpectedFailNum;

                    end


                    %% =====================================
                    % 11. 期望利润
                    %% =====================================

                    ExpectedProfit = ...
                        S - ExpectedCost;


                    %% =====================================
                    % 12. 保存全部结果
                    %% =====================================

                    all_result(row_id,:) = [ ...
                        case_id, ...
                        x1, ...
                        x2, ...
                        x3, ...
                        x4, ...
                        q, ...
                        C1_init, ...
                        C2_init, ...
                        RecoveryCost, ...
                        FutureKnownGoodCost, ...
                        ExpectedFailNum, ...
                        ExpectedReturnNum, ...
                        ExpectedCost, ...
                        ExpectedProfit ...
                        ];

                end

            end

        end

    end

end


%% =========================================================
% 13. 转成 Table
%% =========================================================

AllTable = array2table( ...
    all_result, ...
    'VariableNames', { ...
    'CaseID', ...
    'CheckPart1', ...
    'CheckPart2', ...
    'CheckProduct', ...
    'Disassemble', ...
    'InitialDefectRate', ...
    'InitialPart1Cost', ...
    'InitialPart2Cost', ...
    'RecoveryCost', ...
    'FutureKnownGoodCost', ...
    'ExpectedFailNum', ...
    'ExpectedReturnNum', ...
    'ExpectedCost', ...
    'ExpectedProfit' ...
    });


%% =========================================================
% 14. 生成策略编号
%% =========================================================

Strategy = strings(height(AllTable),1);

for i = 1:height(AllTable)

    Strategy(i) = sprintf( ...
        '%d%d%d%d', ...
        AllTable.CheckPart1(i), ...
        AllTable.CheckPart2(i), ...
        AllTable.CheckProduct(i), ...
        AllTable.Disassemble(i));

end

AllTable.Strategy = Strategy;


%% =========================================================
% 15. 自动识别所有最优方案
%
% 注意：
% 如果出现并列最优，不再只保留第一个
%% =========================================================

Optimal = false(height(AllTable),1);

tol = 1e-8;


for case_id = 1:numCases

    idx = ...
        AllTable.CaseID == case_id;


    tempProfit = ...
        AllTable.ExpectedProfit(idx);


    maxProfit = max(tempProfit);


    caseRows = find(idx);


    tieLocal = ...
        abs(tempProfit - maxProfit) <= tol;


    tieRows = ...
        caseRows(tieLocal);


    Optimal(tieRows) = true;

end


AllTable.Optimal = Optimal;


%% =========================================================
% 16. 提取所有最优策略
%% =========================================================

BestTable = ...
    AllTable(AllTable.Optimal,:);


%% =========================================================
% 17. 输出全部最优策略
%% =========================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('2024 B题 问题2：各情况最优策略\n');
fprintf('============================================================\n');

disp( ...
    BestTable(:,{ ...
    'CaseID', ...
    'Strategy', ...
    'CheckPart1', ...
    'CheckPart2', ...
    'CheckProduct', ...
    'Disassemble', ...
    'InitialDefectRate', ...
    'ExpectedCost', ...
    'ExpectedProfit'}));


%% =========================================================
% 18. 输出中文说明
%% =========================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('最优策略详细说明\n');
fprintf('============================================================\n');


for case_id = 1:numCases

    rows = ...
        BestTable.CaseID == case_id;


    temp = ...
        BestTable(rows,:);


    fprintf('\n情况 %d：\n', case_id);


    if height(temp) > 1

        fprintf('存在 %d 个并列最优策略。\n', ...
            height(temp));

    end


    for j = 1:height(temp)

        fprintf('\n策略 %s：\n', ...
            temp.Strategy(j));


        if temp.CheckPart1(j) == 1
            fprintf('  零件1：检测\n');
        else
            fprintf('  零件1：不检测\n');
        end


        if temp.CheckPart2(j) == 1
            fprintf('  零件2：检测\n');
        else
            fprintf('  零件2：不检测\n');
        end


        if temp.CheckProduct(j) == 1
            fprintf('  成品：检测\n');
        else
            fprintf('  成品：不检测\n');
        end


        if temp.Disassemble(j) == 1
            fprintf('  不合格成品：拆解\n');
        else
            fprintf('  不合格成品：不拆解\n');
        end


        fprintf('  初始成品次品率：%.4f\n', ...
            temp.InitialDefectRate(j));

        fprintf('  期望失败次数：%.4f\n', ...
            temp.ExpectedFailNum(j));

        fprintf('  期望市场退换次数：%.4f\n', ...
            temp.ExpectedReturnNum(j));

        fprintf('  期望总成本：%.4f 元\n', ...
            temp.ExpectedCost(j));

        fprintf('  期望利润：%.4f 元\n', ...
            temp.ExpectedProfit(j));

    end

end


