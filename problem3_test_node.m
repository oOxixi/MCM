clc;
clear;

%% =========================================================
% test_node.m
%
% 目的：
% 只测试：
%
% 零件1、零件2、零件3
%          ↓
%       半成品1
%
% 暂时不做65536种策略枚举
%% =========================================================


%% 1. 零件1~3参数

p = [0.10, 0.10, 0.10];

price = [2, 8, 12];

detectCost = [1, 1, 2];


%% 2. 设置一个测试策略
%
% x1 = 1：检测零件1
% x2 = 0：不检测零件2
% x3 = 1：检测零件3

x = [1, 0, 1];


%% 3. 建立三个零件节点

parts = repmat( ...
    struct( ...
    'C',0, ...
    'g',0, ...
    'detectCost',0, ...
    'inspected',0, ...
    'R',0), ...
    1,3);


for i = 1:3

    parts(i).detectCost = detectCost(i);

    parts(i).inspected = x(i);


    %% -----------------------------------------
    % K / R：
    %
    % 获得一个确认合格零件的期望成本
    %% -----------------------------------------

    K = ...
        (price(i) + detectCost(i)) ...
        / (1-p(i));


    parts(i).R = K;


    %% -----------------------------------------
    % 根据初始是否检测，
    % 决定进入半成品装配时的成本和合格率
    %% -----------------------------------------

    if x(i) == 1

        % 检测：
        % 不合格重新购买、检测直到合格

        parts(i).C = K;

        parts(i).g = 1;

    else

        % 不检测：
        % 买一个直接进入装配

        parts(i).C = price(i);

        parts(i).g = 1-p(i);

    end

end


%% 4. 显示三个零件状态

fprintf('\n');
fprintf('============================================\n');
fprintf('零件节点\n');
fprintf('============================================\n');

for i = 1:3

    fprintf('\n零件%d：\n',i);

    fprintf('  是否检测 = %d\n', ...
        parts(i).inspected);

    fprintf('  当前成本 C = %.6f\n', ...
        parts(i).C);

    fprintf('  合格概率 g = %.6f\n', ...
        parts(i).g);

    fprintf('  已知坏件后的替换成本 R = %.6f\n', ...
        parts(i).R);

end


%% =========================================================
% 5. 半成品1参数
%% =========================================================

semi_p = 0.10;

assemblyCost = 8;

semiDetectCost = 4;

disassemblyCost = 6;


%% 半成品1检测

inspectSemi = 1;


%% 半成品1若检测为次品，则拆解

disassembleSemi = 1;


%% =========================================================
% 6. 调用 evaluate_node.m
%% =========================================================

semi1 = evaluate_node( ...
    parts, ...
    semi_p, ...
    assemblyCost, ...
    semiDetectCost, ...
    disassemblyCost, ...
    inspectSemi, ...
    disassembleSemi);


%% =========================================================
% 7. 输出测试结果
%% =========================================================

fprintf('\n');
fprintf('============================================\n');
fprintf('半成品1测试结果\n');
fprintf('============================================\n');

fprintf('\n第一次装配实际合格率 G：\n');
fprintf('%.6f\n', ...
    semi1.rawGoodRate);

fprintf('\n第一次装配实际次品率 q：\n');
fprintf('%.6f\n', ...
    semi1.rawDefectRate);

fprintf('\n拆解后的零件回收处理成本 RecoveryCost：\n');
fprintf('%.6f 元\n', ...
    semi1.recoveryCost);

fprintf('\n全部零件已知合格后的后续成本 W：\n');
fprintf('%.6f 元\n', ...
    semi1.W);

fprintf('\n已知半成品1为次品后的处理成本 R：\n');
fprintf('%.6f 元\n', ...
    semi1.R);

fprintf('\n从零开始获得确认合格半成品1的成本 K：\n');
fprintf('%.6f 元\n', ...
    semi1.K);

fprintf('\n正常策略下半成品1进入上一层的成本 C：\n');
fprintf('%.6f 元\n', ...
    semi1.C);

fprintf('\n半成品1进入上一层时的合格概率 g：\n');
fprintf('%.6f\n', ...
    semi1.g);

fprintf('\n============================================\n');
fprintf('测试完成\n');
fprintf('============================================\n');