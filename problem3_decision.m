% 24. 模型假设
%% =========================================================

Assumptions = {

    '问题3模型主要假设';

    '1. 不同零配件的质量状态相互独立。';

    '2. 各装配环节发生次品的随机事件相互独立。';

    '3. 所有检测均完全准确，不存在误检和漏检。';

    '4. 零配件供应充足，各次采购参数保持稳定。';

    '5. 拆解过程不会损坏下级零配件或半成品。';

    '6. 拆解后，进入该装配环节之前已经检测过的下级产品不重复检测。';

    '7. 拆解后，进入该装配环节之前没有检测过的下级产品必须检测。';

    '8. 拆解后检测发现下级产品为次品时，按照该下级节点自身的拆解或报废决策继续处理。';

    '9. 最终成品不检测时，次品进入市场后产生40元调换损失。';

    '10. 报废产品残值视为0。';

    '11. 以最终成功向用户交付一件合格产品作为一个完整生产周期。';

    '12. 假设市场需求充足。';

    '13. 忽略库存、产能、时间和资金时间价值。'

    };


