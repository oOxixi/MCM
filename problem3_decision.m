clc;
clear;

%% =========================================================
% 2024 全国大学生数学建模竞赛 B题 问题3
%
% 多工序生产过程决策优化
%
% 生产结构：
%
% 零件1、2、3  --> 半成品1
% 零件4、5、6  --> 半成品2
% 零件7、8     --> 半成品3
%
% 半成品1、2、3 --> 最终成品 --> 市场
%
% =========================================================
%
% 决策变量：
%
% x1~x8：
% 是否检测零件1~8
%
% y1~y3：
% 是否检测半成品1~3
%
% z：
% 是否检测最终成品
%
% u1~u3：
% 半成品不合格后是否拆解
%
% v：
% 最终不合格成品是否拆解
%
% 共：
%
% 8 + 3 + 1 + 3 + 1 = 16
%
% 因此策略总数：
%
% 2^16 = 65536
%
% 优化目标：
%
% 最大化最终成功交付一件合格产品的期望利润
%% =========================================================


%% =========================================================
% 1. 零件参数
%% =========================================================

% 8种零件次品率
part_p = [ ...
    0.10 0.10 0.10 0.10 ...
    0.10 0.10 0.10 0.10];


% 8种零件购买单价
part_price = [ ...
    2 8 12 2 8 12 8 12];


% 8种零件检测成本
part_detect = [ ...
    1 1 2 1 1 2 1 2];


%% =========================================================
% 2. 半成品参数
%% =========================================================

% 三个半成品次品率
semi_p = [ ...
    0.10 0.10 0.10];


% 三个半成品装配成本
semi_assembly = [ ...
    8 8 8];


% 三个半成品检测成本
semi_detect = [ ...
    4 4 4];


% 三个半成品拆解费用
semi_disassembly = [ ...
    6 6 6];


%% =========================================================
% 3. 最终成品参数
%% =========================================================

final_p = 0.10;

final_assembly = 8;

final_detect = 6;

final_disassembly = 10;

sale_price = 200;

replacement_loss = 40;


%% =========================================================
% 4. 枚举规模
%% =========================================================

numDecision = 16;

numStrategies = 2^numDecision;


fprintf('\n');
fprintf('============================================================\n');
fprintf('2024 B题 问题3\n');
fprintf('开始枚举全部 %d 种策略\n',numStrategies);
fprintf('============================================================\n');


%% =========================================================
% 5. 建立结果矩阵
%
% 共25列：
%
% 1~8：
% x1~x8
%
% 9~11：
% y1~y3
%
% 12：
% z
%
% 13~15：
% u1~u3
%
% 16：
% v
%
% 17~19：
% 三个半成品进入最终装配时的合格概率
%
% 20：
% 最终成品第一次装配的合格率
%
% 21：
% 最终成品第一次装配的次品率
%
% 22：
% 最终成品拆解后的半成品回收处理成本
%
% 23：
% 最终成功交付的期望总成本
%
% 24：
% 期望利润
%
% 25：
% 策略编号
%% =========================================================

result = zeros(numStrategies,25);

Strategy = strings(numStrategies,1);


%% =========================================================
% 6. 遍历65536种策略
%% =========================================================

for strategy_id = 0:numStrategies-1

    row = strategy_id + 1;


    %% -----------------------------------------------------
    % 十进制编号转换成16个0-1变量
    %% -----------------------------------------------------

    bits = double( ...
        bitget(uint32(strategy_id),1:16) ...
        );


    %% -----------------------------------------------------
    % 决策变量拆分
    %% -----------------------------------------------------

    % 零件检测
    x = bits(1:8);

    % 半成品检测
    y = bits(9:11);

    % 最终成品检测
    z = bits(12);

    % 半成品拆解
    u = bits(13:15);

    % 最终成品拆解
    v = bits(16);


    %% =====================================================
    % 7. 第一层：建立8个零件节点
    %% =====================================================

    parts = repmat( ...
        struct( ...
        'C',0, ...
        'g',0, ...
        'detectCost',0, ...
        'inspected',0, ...
        'R',0), ...
        1,8);


    for i = 1:8

        %% 已知坏零件后，
        % 获得一个确认合格零件的期望成本

        K_part = ...
            ( ...
            part_price(i) ...
            + part_detect(i) ...
            ) ...
            / (1-part_p(i));


        %% 零件检测成本

        parts(i).detectCost = ...
            part_detect(i);


        %% 是否已经检测

        parts(i).inspected = ...
            x(i);


        %% 已知当前零件为次品：
        % 丢弃并重新采购、检测直到合格

        parts(i).R = ...
            K_part;


        %% -----------------------------------------
        % 当前生产策略下的成本和合格率
        %% -----------------------------------------

        if x(i) == 1

            % 检测零件：
            %
            % 不合格则不断重新采购和检测
            % 直到得到合格件

            parts(i).C = ...
                K_part;

            parts(i).g = ...
                1;

        else

            % 不检测：
            %
            % 购买后直接进入装配

            parts(i).C = ...
                part_price(i);

            parts(i).g = ...
                1-part_p(i);

        end

    end


    %% =====================================================
    % 8. 第二层：半成品1
    %
    % 零件1、2、3
    %% =====================================================

    semi1 = evaluate_node( ...
        parts(1:3), ...
        semi_p(1), ...
        semi_assembly(1), ...
        semi_detect(1), ...
        semi_disassembly(1), ...
        y(1), ...
        u(1));


    %% =====================================================
    % 9. 半成品2
    %
    % 零件4、5、6
    %% =====================================================

    semi2 = evaluate_node( ...
        parts(4:6), ...
        semi_p(2), ...
        semi_assembly(2), ...
        semi_detect(2), ...
        semi_disassembly(2), ...
        y(2), ...
        u(2));


    %% =====================================================
    % 10. 半成品3
    %
    % 零件7、8
    %% =====================================================

    semi3 = evaluate_node( ...
        parts(7:8), ...
        semi_p(3), ...
        semi_assembly(3), ...
        semi_detect(3), ...
        semi_disassembly(3), ...
        y(3), ...
        u(3));


    %% 三个半成品组成数组

    semis = [ ...
        semi1 ...
        semi2 ...
        semi3 ...
        ];


    %% =====================================================
    % 11. 第三层：最终成品
    %% =====================================================

    final = evaluate_final( ...
        semis, ...
        final_p, ...
        final_assembly, ...
        final_detect, ...
        final_disassembly, ...
        replacement_loss, ...
        z, ...
        v);


    %% =====================================================
    % 12. 期望总成本
    %% =====================================================

    ExpectedCost = ...
        final.C;


    %% =====================================================
    % 13. 期望利润
    %
    % 一件最终成功交付产品只获得一次售价收入
    %% =====================================================

    ExpectedProfit = ...
        sale_price - ExpectedCost;


    %% =====================================================
    % 14. 保存策略
    %% =====================================================

    result(row,1:16) = bits;

    result(row,17) = ...
        semi1.g;

    result(row,18) = ...
        semi2.g;

    result(row,19) = ...
        semi3.g;

    result(row,20) = ...
        final.goodRate;

    result(row,21) = ...
        final.defectRate;

    result(row,22) = ...
        final.recoveryCost;

    result(row,23) = ...
        ExpectedCost;

    result(row,24) = ...
        ExpectedProfit;

    result(row,25) = ...
        strategy_id;


    %% =====================================================
    % 15. 生成16位策略编码
    %
    % 顺序：
    %
    % x1 x2 x3 x4 x5 x6 x7 x8
    % y1 y2 y3
    % z
    % u1 u2 u3
    % v
    %% =====================================================

    Strategy(row) = sprintf( ...
        '%d%d%d%d%d%d%d%d%d%d%d%d%d%d%d%d', ...
        bits(1),bits(2),bits(3),bits(4), ...
        bits(5),bits(6),bits(7),bits(8), ...
        bits(9),bits(10),bits(11), ...
        bits(12), ...
        bits(13),bits(14),bits(15), ...
        bits(16));

end


%% =========================================================
% 16. 转换成Table
%% =========================================================

AllTable = array2table( ...
    result, ...
    'VariableNames', { ...
    'x1','x2','x3','x4', ...
    'x5','x6','x7','x8', ...
    'y1','y2','y3', ...
    'z', ...
    'u1','u2','u3', ...
    'v', ...
    'Semi1GoodRate', ...
    'Semi2GoodRate', ...
    'Semi3GoodRate', ...
    'FinalGoodRate', ...
    'FinalDefectRate', ...
    'RecoveryCost', ...
    'ExpectedCost', ...
    'ExpectedProfit', ...
    'StrategyID' ...
    });


AllTable.Strategy = Strategy;


%% =========================================================
% 17. 找出最大期望利润
%% =========================================================

maxProfit = ...
    max(AllTable.ExpectedProfit);


%% MATLAB浮点数容差

tol = 1e-8;


Optimal = ...
    abs( ...
    AllTable.ExpectedProfit ...
    - maxProfit ...
    ) <= tol;


AllTable.Optimal = ...
    Optimal;


%% =========================================================
% 18. 提取所有并列最优策略
%% =========================================================

BestTable = ...
    AllTable(Optimal,:);


%% =========================================================
% 19. 按利润从高到低排序
%% =========================================================

SortedTable = ...
    sortrows( ...
    AllTable, ...
    'ExpectedProfit', ...
    'descend');


%% 保存前20名

TopTable = ...
    SortedTable( ...
    1:min(20,height(SortedTable)), ...
    :);


%% =========================================================
% 20. 输出最优方案
%% =========================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('问题3计算完成\n');
fprintf('============================================================\n');

fprintf('\n最大期望利润：%.6f 元\n', ...
    maxProfit);

fprintf('最优策略数量：%d\n\n', ...
    height(BestTable));


disp( ...
    BestTable(:,{ ...
    'Strategy', ...
    'x1','x2','x3','x4', ...
    'x5','x6','x7','x8', ...
    'y1','y2','y3', ...
    'z', ...
    'u1','u2','u3', ...
    'v', ...
    'FinalDefectRate', ...
    'ExpectedCost', ...
    'ExpectedProfit' ...
    }) ...
    );


%% =========================================================
% 21. 输出中文决策说明
%% =========================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('最优方案详细说明\n');
fprintf('============================================================\n');


for k = 1:height(BestTable)

    fprintf('\n');
    fprintf('------------------------------------------------------------\n');
    fprintf('最优策略 %d：%s\n', ...
        k,BestTable.Strategy(k));
    fprintf('------------------------------------------------------------\n');


    %% -----------------------------------------------------
    % 零件检测
    %% -----------------------------------------------------

    fprintf('\n零件检测决策：\n');


    for i = 1:8

        value = ...
            BestTable{k,['x' num2str(i)]};


        if value == 1

            fprintf( ...
                '零件%d：检测\n',i);

        else

            fprintf( ...
                '零件%d：不检测\n',i);

        end

    end


    %% -----------------------------------------------------
    % 半成品检测
    %% -----------------------------------------------------

    fprintf('\n半成品检测决策：\n');


    for j = 1:3

        value = ...
            BestTable{k,['y' num2str(j)]};


        if value == 1

            fprintf( ...
                '半成品%d：检测\n',j);

        else

            fprintf( ...
                '半成品%d：不检测\n',j);

        end

    end


    %% -----------------------------------------------------
    % 最终成品检测
    %% -----------------------------------------------------

    fprintf('\n最终成品：');


    if BestTable.z(k) == 1

        fprintf('检测\n');

    else

        fprintf('不检测\n');

    end


    %% -----------------------------------------------------
    % 半成品拆解
    %% -----------------------------------------------------

    fprintf('\n半成品不合格后的处理：\n');


    for j = 1:3

        value = ...
            BestTable{k,['u' num2str(j)]};


        if value == 1

            fprintf( ...
                '半成品%d：拆解\n',j);

        else

            fprintf( ...
                '半成品%d：不拆解\n',j);

        end

    end


    %% -----------------------------------------------------
    % 最终成品拆解
    %% -----------------------------------------------------

    fprintf('\n最终不合格成品：');


    if BestTable.v(k) == 1

        fprintf('拆解\n');

    else

        fprintf('不拆解\n');

    end


    %% -----------------------------------------------------
    % 成本与利润
    %% -----------------------------------------------------

    fprintf( ...
        '\n最终产品第一次装配实际次品率：%.6f\n', ...
        BestTable.FinalDefectRate(k));


    fprintf( ...
        '最终成功交付一件合格产品的期望总成本：%.6f 元\n', ...
        BestTable.ExpectedCost(k));


    fprintf( ...
        '最终期望利润：%.6f 元\n', ...
        BestTable.ExpectedProfit(k));

end


%% =========================================================
% 22. 保存Excel
%% =========================================================

filename = ...
    'problem3_result.xlsx';


if exist(filename,'file')

    delete(filename);

end


